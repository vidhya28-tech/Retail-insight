from pathlib import Path
import json
import pandas as pd
import streamlit as st
import plotly.express as px

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/"data/processed/retail_public.csv"
st.set_page_config(page_title="Retail Insight Lab",page_icon="📊",layout="wide")
st.markdown("""<style>
.stApp{background:#F5F0E8;color:#3B3028}.block-container{max-width:1440px;padding-top:2rem}
[data-testid='stMetric']{background:#FFFCF7;padding:1.15rem 1.3rem;border:1px solid #e9dfd2;border-radius:16px}
[data-testid='stSidebar']{background:#FFFCF7}h1,h2,h3{color:#3B3028}div[data-testid='stAlert']{border-radius:14px}
</style>""",unsafe_allow_html=True)
st.title("Retail Insight Lab")
st.caption("Retail business performance & profitability analysis · Evidence-led · Source values preserved")
if not DATA.exists():
    st.warning("Analysis is waiting for the source workbook. No sample or fabricated results are shown.")
    st.markdown("Place **sample_-_superstore.xls** in `data/raw/`, install the requirements, then run `python src/analysis.py` from the project root. This dashboard reads `data/processed/retail_cleaned.csv` generated by that pipeline.")
    st.info("This dataset was not available in the project workspace during creation. Add the actual workbook before interpreting findings. The SQL/Python project and dashboard are ready to run against its real columns.")
    st.subheader("Inventory evidence requirement")
    st.write("Sales velocity is a demand proxy, not inventory turnover. No product will be labelled overstocked without stock-on-hand, receipts, stockouts, and lead-time data.")
    st.stop()
df=pd.read_csv(DATA,parse_dates=[c for c in ["Order Date"] if c in pd.read_csv(DATA,nrows=0).columns])
results_path=ROOT/"reports/analysis_results.json"
filters={}
with st.sidebar:
    st.header("Explore the data")
    for col,label in [("Region","Region"),("Category","Category"),("Sub-Category","Sub-category"),("Season","Season"),("Segment","Segment")]:
        if col in df:
            options=sorted(df[col].dropna().astype(str).unique())
            filters[col]=st.multiselect(label,options,default=options)
    if "Order Date" in df:
        lo,hi=df["Order Date"].min().date(),df["Order Date"].max().date()
        dates=st.date_input("Order date range",(lo,hi),min_value=lo,max_value=hi)
        if isinstance(dates,tuple) and len(dates)==2: df=df[df["Order Date"].dt.date.between(dates[0],dates[1])]
    for col,selected in filters.items():
        if selected: df=df[df[col].astype(str).isin(selected)]
    st.divider(); st.caption("Currency remains in source units unless USD is confirmed. INR conversion assumption can be configured in project report (₹84 per USD), not a live rate.")
page=st.selectbox("Analysis page",["Executive overview","Category & sub-category","Regional performance","Seasonal & monthly","Discount impact","Product performance","Returns analysis","Data quality & inventory"])
sales=float(df.Sales.sum()) if "Sales" in df else 0; profit=float(df.Profit.sum()) if "Profit" in df else 0
margin=profit/sales*100 if sales else 0
orders=df["Order ID"].nunique() if "Order ID" in df else len(df)
units=df.Quantity.sum() if "Quantity" in df else 0
if page=="Executive overview":
    st.subheader("Executive overview")
    a,b,c,d=st.columns(4); a.metric("Sales",f"{sales:,.2f}"); b.metric("Profit",f"{profit:,.2f}"); c.metric("Profit margin",f"{margin:.2f}%"); d.metric("Orders",f"{orders:,}")
    st.caption(f"Units sold: {units:,.0f} · {len(df):,} transaction rows in current filters")
    left,right=st.columns(2)
    if "Category" in df and "Profit" in df: left.plotly_chart(px.bar(df.groupby("Category",as_index=False).Profit.sum(),x="Category",y="Profit",color_discrete_sequence=["#A85D45"],title="Profit by category"),use_container_width=True)
    if "Order Date" in df and "Sales" in df: right.plotly_chart(px.line(df.assign(Month=df["Order Date"].dt.to_period("M").astype(str)).groupby("Month",as_index=False).Sales.sum(),x="Month",y="Sales",title="Monthly sales",color_discrete_sequence=["#708DA3"]),use_container_width=True)
elif page in ["Category & sub-category","Regional performance"]:
    key="Category" if page.startswith("Category") else "Region"
    st.subheader(page)
    if key in df:
        table=df.groupby([key]+(["Sub-Category"] if key=="Category" and "Sub-Category" in df else []),as_index=False).agg(Sales=("Sales","sum"),Profit=("Profit","sum"))
        table["Profit Margin (%)"]=100*table.Profit/table.Sales.replace(0,pd.NA)
        st.plotly_chart(px.bar(table,x=key,y="Profit",color="Profit",color_continuous_scale=["#C8907D","#7D9676"],title="Profitability by grouping"),use_container_width=True); st.dataframe(table,use_container_width=True,hide_index=True)
elif page=="Seasonal & monthly":
    st.subheader(page)
    if "Season" in df: st.plotly_chart(px.bar(df.groupby("Season",as_index=False).Sales.sum(),x="Season",y="Sales",color_discrete_sequence=["#7D9676"]),use_container_width=True)
    if "Order Date" in df: st.plotly_chart(px.line(df.assign(Month=df["Order Date"].dt.to_period("M").astype(str)).groupby("Month",as_index=False).Sales.sum(),x="Month",y="Sales",color_discrete_sequence=["#A85D45"]),use_container_width=True)
elif page=="Discount impact":
    st.subheader(page); st.caption("Descriptive association; discounts are not treated as causal evidence.")
    if "Discount" in df: st.plotly_chart(px.scatter(df,x="Discount",y="Profit",color="Category" if "Category" in df else None,opacity=.55),use_container_width=True)
elif page=="Product performance":
    st.subheader(page); st.caption("Sales velocity proxy = units sold / calendar months in the selected observations. Not inventory turnover.")
    if "Product Name" in df:
        products=df.groupby("Product Name",as_index=False).agg(Sales=("Sales","sum"),Profit=("Profit","sum"),Units=("Quantity","sum") if "Quantity" in df else ("Sales","count"))
        st.dataframe(products.sort_values("Sales",ascending=False).head(30),use_container_width=True,hide_index=True)
elif page=="Returns analysis":
    st.subheader(page)
    if "Returned" in df or "Return" in df: st.write("Returns field detected. Use distinct order-level counts when interpreting return rates.")
    else: st.info("No returns field/table was found in the cleaned transaction data; return rates are unavailable.")
else:
    st.subheader("Data quality & inventory limitations")
    quality_path=ROOT/"data/processed/data_quality.json"
    if quality_path.exists(): st.json(json.loads(quality_path.read_text(encoding="utf-8")))
    st.warning("Without stock levels, inventory days, warehouse quantities, and lead times, inventory turnover and stockout-adjusted demand cannot be calculated. Low sales alone do not establish overstock.")
    st.write("Collect dated SKU-location stock snapshots, sales at daily grain, purchase receipts, stockout periods, and supplier lead times.")
